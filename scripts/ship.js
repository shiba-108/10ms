#!/usr/bin/env node
// scripts/ship.js
// One command must compile, seal, and deploy the same source. P3 · P7 · D18.
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const { lex } = require('../src/core/lex');
const { parse } = require('../src/core/parse');
const { cost } = require('../src/core/cost');
const { seal } = require('../src/core/seal');
const { typeCheck } = require('../src/core/type');

const ROOT = path.resolve(__dirname, '..');
const ENTRY = path.join(ROOT, '.wrangler', 'cloudflare.js');

// Keep validation and sealing in the build step, off the request path. P1 · P4 · D14 · D18.
function compileSource(source) {
  const { tokens, seed } = lex(source);
  const ast = parse(tokens, seed);
  typeCheck(ast, seed);
  const budget = cost(ast, seed);
  if (!ast.body.some((node) => node.type === 'Page')) {
    const e = new Error('ship');
    e.detail = {
      error: 'ship',
      pos: { line: 1, col: 1 },
      expected: 'a Web program containing page /',
      fix: 'add page / followed by an indented body',
      seed,
    };
    throw e;
  }
  return { ast, seed, seal: seal(source), budget };
}

// Embed only the checked AST and its seal in the Wrangler entry. P4 · D18.
function buildEntry(program) {
  const shipped = { ast: program.ast, seed: program.seed, seal: program.seal };
  return [
    '// Generated by scripts/ship.js; edit the .10ms source instead.',
    "const { createSealedWorker } = require('../src/host/worker/ship');",
    `const app = createSealedWorker(${JSON.stringify(shipped)});`,
    'export default {',
    '  fetch(request) { return app.fetch(request); },',
    '  scheduled(_controller, _env, context) { context.waitUntil(app.scheduled({})); },',
    '};',
    '',
  ].join('\n');
}

// Validate and write the build artifact before letting Wrangler publish it. P3 · P7 · D18.
function main(argv) {
  if (argv.includes('--help') || argv.includes('-h')) {
    console.log('Usage: node scripts/ship.js [source.10ms] [--dry-run]');
    return 0;
  }
  const dryRun = argv.includes('--dry-run');
  const files = argv.filter((arg) => arg !== '--dry-run');
  if (files.length > 1 || (files[0] && files[0].startsWith('-'))) {
    console.error('Usage: node scripts/ship.js [source.10ms] [--dry-run]');
    return 2;
  }
  const sourcePath = path.resolve(ROOT, files[0] || 'web.10ms');
  let source;
  try {
    source = fs.readFileSync(sourcePath, 'utf8');
  } catch (error) {
    console.error(`SHIP_SOURCE_NOT_FOUND: ${path.relative(ROOT, sourcePath)}`);
    return 1;
  }
  let program;
  try {
    program = compileSource(source);
  } catch (error) {
    console.error(JSON.stringify(error.detail || { error: 'ship', message: error.message }));
    return 1;
  }
  fs.mkdirSync(path.dirname(ENTRY), { recursive: true });
  fs.writeFileSync(ENTRY, buildEntry(program));
  console.log(`Source: ${path.relative(ROOT, sourcePath)}`);
  console.log(`Seal: ${program.seal}`);
  console.log(`Cost proof: ${program.budget.ms.toFixed(3)}ms / ${program.budget.budget_ms}ms`);
  if (dryRun) console.log('Mode: Wrangler dry run');

  const npx = process.platform === 'win32' ? 'npx.cmd' : 'npx';
  const args = ['--yes', 'wrangler@4.168.0', 'deploy', '--config', 'wrangler.toml'];
  if (dryRun) args.push('--dry-run');
  const result = spawnSync(npx, args, { cwd: ROOT, encoding: 'utf8' });
  if (result.stdout) process.stdout.write(result.stdout);
  if (result.stderr) process.stderr.write(result.stderr);
  if (result.error) {
    console.error(`WRANGLER_FAILED: ${result.error.message}`);
    return 1;
  }
  if (result.status !== 0) return result.status || 1;
  if (!dryRun) {
    const output = `${result.stdout || ''}\n${result.stderr || ''}`;
    const url = output.match(/https:\/\/[a-z0-9.-]+\.workers\.dev(?:\/[^\s)]*)?/i);
    if (url) console.log(`URL: ${url[0]}`);
  }
  return 0;
}

if (require.main === module) process.exitCode = main(process.argv.slice(2));
module.exports = { buildEntry, compileSource };
